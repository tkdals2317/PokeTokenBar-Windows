/** Korean particle after `word`: `withCoda` when its last syllable has a final consonant, else `without`
 * (KoreanParticle.swift). `rieulTakesShort`: ㄹ takes the short form (으로/로). Non-Hangul → "이(가)" style. */
export function josa(word: string, withCoda: string, without: string, rieulTakesShort = false): string {
  const c = word.codePointAt(word.length - 1) ?? 0;
  if (c < 0xac00 || c > 0xd7a3) return word + (rieulTakesShort ? "(으)로" : `${withCoda}(${without})`);
  const coda = (c - 0xac00) % 28;
  return word + (coda === 0 || (rieulTakesShort && coda === 8) ? without : withCoda);
}

