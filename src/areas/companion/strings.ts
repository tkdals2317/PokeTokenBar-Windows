/** Korean particle after a runtime name (KoreanParticle.swift). Non-Hangul keeps the dual form. */
export function particle(word: string, kind: "subject" | "object" | "direction") {
  const last = word.codePointAt(word.length - 1) ?? 0;
  const coda = last >= 0xac00 && last <= 0xd7a3 ? (last - 0xac00) % 28 : null;
  if (kind === "subject") return word + (coda == null ? "이(가)" : coda === 0 ? "가" : "이");
  if (kind === "object") return word + (coda == null ? "을(를)" : coda === 0 ? "를" : "을");
  return word + (coda == null ? "(으)로" : coda === 0 || coda === 8 ? "로" : "으로");
}

